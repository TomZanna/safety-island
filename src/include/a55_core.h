/*
 * a55_core.h
 *
 * The A55 "black channel" thread: the communication engine that, on the
 * target, runs the EtherCAT fieldbus stack and exchanges the safety frames
 * with the two safety cores through the SHMEM mailbox.
 *
 * On the PC the fieldbus is emulated in-process with a real rt-labs FSoE
 * slave stack (loopback strategy, see pseudo_code.md section 3.1): the frames
 * committed by M7/M33 in the SHMEM are fed to the slave stack and the slave
 * replies are published back into the SHMEM. The A55 also simulates the field
 * process image (E-stop channels, guard door, reset button) and prints what it
 * reads from the shared memory.
 */

#ifndef A55_CORE_H
#define A55_CORE_H

#include "flow_config.h"
#include "flow_rng.h"
#include "flow_setup.h"
#include "fsoe_app_glue.h"
#include "fsoe_slot.h"
#include "safe_logic.h"
#include "shmem_mailbox.h"

#include <fsoeslave.h>

#include <stdatomic.h>
#include <stdbool.h>
#include <stdint.h>

typedef struct flow_a55_stats
{
   uint32_t bus_cycles;
   uint32_t tx_frames_read;      /**< Frames taken from the SHMEM TX channel   */
   uint32_t tx_frames_dropped;   /**< Frames dropped on purpose (fault)        */
   uint32_t slave_frames_published;
   uint32_t publish_deferred;
   uint32_t master_frames_delivered; /**< Frames handed to the slave stack     */
   uint32_t slave_frames_in;
   uint32_t slave_frames_out;
   uint32_t process_data_cycles;
   uint32_t state_changes;
   uint32_t session_ids;
   uint32_t actuator_enable_changes;
} flow_a55_stats_t;

typedef struct flow_a55_env
{
   flow_shmem_t * shm;
   flow_fault_cfg_t * fault;
   const flow_cli_config_t * cfg;
   flow_rng_t * rng;
   atomic_bool * stop;
   atomic_uint * slave_session_id;
} flow_a55_env_t;

typedef struct flow_a55_core
{
   flow_a55_env_t env;

   fsoeslave_t slave[FLOW_NUM_CONNECTIONS];
   flow_app_ctx_t ctx[FLOW_NUM_CONNECTIONS];

   /* Frame read from the SHMEM and waiting to be given to the slave stack */
   flow_fsoe_slot_t pending_master[FLOW_NUM_CONNECTIONS];
   bool pending_master_ready[FLOW_NUM_CONNECTIONS];
   uint32_t last_tx_published[FLOW_NUM_CONNECTIONS];

   /* Frame generated by the slave stack and waiting to be published to SHMEM */
   flow_fsoe_slot_t pending_slave[FLOW_NUM_CONNECTIONS];
   bool pending_slave_ready[FLOW_NUM_CONNECTIONS];
   uint32_t rx_frames[FLOW_NUM_CONNECTIONS];

   /* Simulated field process image */
   flow_safe_inputs_t field_inputs[FLOW_NUM_CONNECTIONS];
   flow_safe_outputs_t field_outputs[FLOW_NUM_CONNECTIONS];
   flow_safe_outputs_t reported_outputs[FLOW_NUM_CONNECTIONS];
   bool field_outputs_valid[FLOW_NUM_CONNECTIONS];

   fsoeslave_syncstatus_t sync[FLOW_NUM_CONNECTIONS];
   fsoeslave_state_t last_state[FLOW_NUM_CONNECTIONS];

   uint32_t bus_cycle;
   flow_a55_stats_t stats;
} flow_a55_core_t;

void flow_a55_core_init (
   flow_a55_core_t * a55,
   const flow_a55_env_t * env);

/** \brief Run the black channel loop until the runtime stop flag is set */
void flow_a55_core_run (flow_a55_core_t * a55);

/** \brief pthread entry point, argument is a flow_a55_core_t * */
void * flow_a55_core_thread (void * argument);

/**
 * \brief Scripted field stimulus (two channel E-stop, door, reset button)
 *
 * The scenario is deterministic in the bus cycle counter, so that the whole
 * demonstration is reproducible.
 */
void flow_a55_field_scenario (
   flow_a55_core_t * a55,
   uint32_t k,
   uint32_t bus_cycle,
   flow_safe_inputs_t * inputs);

#endif /* A55_CORE_H */
