/*
 * fsoe_app_glue.h
 *
 * Application side of the rt-labs FSoE stack.
 *
 * The stack calls five global application callbacks (fsoeapp_send(),
 * fsoeapp_recv(), fsoeapp_generate_session_id(), fsoeapp_verify_parameters(),
 * fsoeapp_handle_user_error()). Since M7, M33 and the A55 slave all live in
 * the same process, a single implementation is linked and it dispatches on the
 * `app_ref` pointer that was given to fsoemaster_init()/fsoeslave_init().
 *
 * On the real target each core has its own binary, so this dispatch is a
 * no-op there; the important part is that the library sees exactly the same
 * API and that no mutable state is shared through globals.
 */

#ifndef FSOE_APP_GLUE_H
#define FSOE_APP_GLUE_H

#include "fsoe_slot.h"

#include <stdbool.h>
#include <stdint.h>

typedef enum flow_ctx_kind
{
   FLOW_CTX_M7 = 0,
   FLOW_CTX_M33 = 1,
   FLOW_CTX_SLAVE = 2
} flow_ctx_kind_t;

#define FLOW_CTX_MAGIC 0x46534F45u /* "FSOE" */

typedef struct flow_app_ctx flow_app_ctx_t;

/**
 * \brief Called by the stack from inside fsoeapp_send()
 *
 * The owner (a safety core or the A55 slave) performs the inter-core
 * cross-check of the generated PDU and the publication of the frame.
 */
typedef void (*flow_app_egress_fn) (
   flow_app_ctx_t * ctx,
   const flow_fsoe_slot_t * frame);

/**
 * \brief Called by the stack from inside fsoeapp_generate_session_id()
 *
 * The owner negotiates the Session ID with the other safety core over the
 * messaging unit and returns the final value.
 */
typedef uint16_t (*flow_app_session_fn) (flow_app_ctx_t * ctx);

struct flow_app_ctx
{
   uint32_t magic;
   flow_ctx_kind_t kind;
   uint32_t k;       /**< FSoE connection index                     */
   void * stack;     /**< fsoemaster_t * or fsoeslave_t *           */
   void * owner;     /**< flow_safe_core_t * or flow_a55_core_t *   */
   flow_app_egress_fn on_egress;
   flow_app_session_fn on_session_id;


   /* RX path: the frame handed to the stack in this cycle */
   flow_fsoe_slot_t rx;
   uint32_t rx_published;
   bool rx_ready;

   /* TX path: the last frame generated by the stack */
   flow_fsoe_slot_t tx;
   bool tx_ready;

   /* Session ID negotiation */
   uint32_t session_rnd;   /**< Local random number of this core        */
   uint32_t session_id;    /**< Negotiated Session ID (sum of both)     */
   uint32_t session_count; /**< Number of negotiations performed        */

   struct
   {
      uint32_t sent;
      uint32_t recv_provided;
      uint32_t recv_consumed;
      uint32_t recv_overwritten;
   } stats;
};

void flow_app_ctx_init (
   flow_app_ctx_t * ctx,
   flow_ctx_kind_t kind,
   uint32_t k,
   void * stack,
   void * owner,
   flow_app_egress_fn on_egress,
   flow_app_session_fn on_session_id);

/** \brief Seed the RNG used by the A55 slave for its Session ID */
void flow_app_glue_init (uint32_t seed);

/** \brief Name of the context kind, for logging */
const char * flow_ctx_kind_name (flow_ctx_kind_t kind);

/** \brief Hand a raw frame to the stack (diagram step 1, local RAM copy) */
void flow_app_ctx_provide_rx (
   flow_app_ctx_t * ctx,
   const flow_fsoe_slot_t * slot,
   uint32_t published);

void flow_app_ctx_clear_rx (flow_app_ctx_t * ctx);

/** \brief Take the frame generated by the stack, if any (A55 side) */
bool flow_app_ctx_take_tx (flow_app_ctx_t * ctx, flow_fsoe_slot_t * slot);

#endif /* FSOE_APP_GLUE_H */
